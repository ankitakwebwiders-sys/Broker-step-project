export type CommissionTransactionType =
  | 'New Business'
  | 'Renewal'
  | 'Endorsement'
  | 'Chargeback'
  | 'Adjustment'
  | 'Cancellation'
  | 'Bonus / Additional'

export type CommissionReconciliationStatus =
  | 'Reconciled'
  | 'Pending'
  | 'Partial Paid'
  | 'Discrepancy'
  | 'In Review'
  | 'Chargeback'

export interface CommissionAuditLog {
  id: string
  timestamp: string
  user: string
  action: string
  previousStatus?: string
  newStatus?: string
  notes?: string
}

export interface CommissionItem {
  id: string
  transactionNumber: string
  transactionDate: string
  transactionType: CommissionTransactionType
  clientId: string
  clientName: string
  businessName: string
  clientEmail: string
  clientPhone: string
  policyId: string
  policyNumber: string
  lineOfBusiness: string
  carrier: string
  statementSource: string
  statementDate: string
  premium: number
  commissionRate: number // e.g. 15 for 15%
  expectedCommission: number
  actualPaidCommission: number
  additionalCommission: number
  chargeback: number
  adjustment: number
  netCommission: number
  reconciliationStatus: CommissionReconciliationStatus
  category: 'expected' | 'paid' | 'outstanding' | 'partial' | 'chargeback' | 'adjustment'
  notes: string
  auditHistory: CommissionAuditLog[]
}

