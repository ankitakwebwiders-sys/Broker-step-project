export type StatementProcessingStatus =
  | 'Uploaded'
  | 'Processing'
  | 'Processed'
  | 'Needs Review'
  | 'Completed'

export type MatchConfidenceTier = 'High Confidence' | 'Possible Match' | 'Unmatched'

export interface StatementTransactionItem {
  id: string
  statementId: string
  lineIndex: number
  rawSourceRow: string
  policyNumber: string
  clientName: string
  businessName: string
  lineOfBusiness: string
  carrier: string
  grossPremium: number
  commissionRate: number
  paidCommission: number
  expectedCommission: number
  variance: number
  matchConfidence: MatchConfidenceTier
  matchScore: number // 0-100
  matchedSystemPolicyId?: string
  ruleMatched: string
  status: 'Auto-Matched' | 'Pending Broker Review' | 'Action Required' | 'Resolved'
  resolutionNote?: string
}

export interface StatementAuditItem {
  id: string
  timestamp: string
  user: string
  action: string
  notes: string
}

export interface StatementRecord {
  id: string
  statementIdentifier: string
  fileName: string
  fileType: 'xlsx' | 'csv' | 'pdf'
  fileSize: string
  carrier: string
  statementPeriod: string
  statementPeriodDate: string
  uploadDate: string
  processingStatus: StatementProcessingStatus
  transactionsCount: number
  matchedCount: number
  unmatchedCount: number
  needsReviewCount: number
  highConfidenceCount: number
  totalRemittance: number
  paymentMethod: string
  batchReference: string
  mappingTemplate: string
  extractedDate: string
  normalizedDate: string
  reprocessedCount: number
  notes: string
  processingPipelineStep: number // 1 to 9
  transactions: StatementTransactionItem[]
  auditHistory: StatementAuditItem[]
}

