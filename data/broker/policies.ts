export type PolicyStatus = 'Active' | 'Pending' | 'Under Review' | 'Expired' | 'Cancelled' | 'Historical'

export type TransactionType =
  | 'New Business'
  | 'Renewal'
  | 'Rewrite'
  | 'Endorsement'
  | 'Cancellation'
  | 'Chargeback'
  | 'Adjustment'

export type ReconciliationStatus = 'Reconciled' | 'Pending' | 'Discrepancy' | 'Unmatched'

export interface PolicyTransactionItem {
  id: string
  date: string
  type: TransactionType
  description: string
  statementNumber?: string
  premiumChange: number
  expectedCommission: number
  actualPaid: number
  outstanding: number
  reconciliationStatus: ReconciliationStatus
  statementDate?: string
  sourceStatementUrl?: string
}

export interface PolicyTimelineEvent {
  id: string
  title: string
  type: 'creation' | 'renewal' | 'rewrite' | 'endorsement' | 'cancellation' | 'chargeback' | 'adjustment' | 'commission' | 'reconciliation'
  date: string
  detail: string
  actor: string
}

export interface PolicyRecord {
  id: string
  policyNumber: string // 'Pending' or format 'POL-...'
  isPendingNumber?: boolean
  clientId: string
  clientName: string
  businessName: string
  clientEmail: string
  clientPhone: string
  carrier: string
  policyStatus: PolicyStatus
  lineOfBusiness: string
  transactionType: TransactionType
  effectiveDate: string
  expiryDate: string
  premium: number
  commissionRate: number // percentage e.g. 15 for 15%
  brokerSplit: number // percentage e.g. 70 for 70%
  expectedCommission: number
  actualPaidCommission: number
  outstandingCommission: number
  reconciliationStatus: ReconciliationStatus
  notes?: string
  sourceStatementNumber?: string
  sourceStatementDate?: string
  sourceStatementCarrier?: string
  transactions: PolicyTransactionItem[]
  timeline: PolicyTimelineEvent[]
}

